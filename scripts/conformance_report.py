"""Generate the compatibility and conformance report from the runners' JSON reports.

The conformance runners (Python `personal_agent_protocol.conformance`, TypeScript
`src/__tests__/support/conformance.mjs`) write one schema-1 report per language
pairing when `PAP_CONFORMANCE_REPORTS` names a directory:

    PAP_CONFORMANCE_REPORTS=reports pytest personal_agent_protocol/__tests__/test_conformance.py \\
        personal_agent_protocol/__tests__/test_cross_language.py
    PAP_CONFORMANCE_REPORTS=reports node --test src/__tests__/conformance-pairing.test.mjs
    python scripts/conformance_report.py reports

writes `docs/docs/protocol/conformance-report.mdx`: the outcome of every case for
every pairing, and the cases each SDK decides alone. The page holds outcomes only
(no timings or dates), so it changes only when a result does.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "docs" / "docs" / "protocol" / "conformance-report.mdx"
SUITES = ("protocol", "security", "lifecycle", "conversations", "operations", "dpop")

#: Every pairing, in the order of the page's columns: (file stem, agent, company).
PAIRINGS = (
    ("python-agent-python-company", "Python", "Python"),
    ("python-agent-typescript-company", "Python", "TypeScript"),
    ("typescript-agent-python-company", "TypeScript", "Python"),
    ("typescript-agent-typescript-company", "TypeScript", "TypeScript"),
)

OUTCOME = {"passed": "pass", "failed": "**fail**", "skipped": "skip"}


def _fixtures() -> list[dict[str, Any]]:
    cases = []
    for suite in SUITES:
        path = ROOT / "protocol" / "fixtures" / "conformance" / f"{suite}.json"
        for raw in json.loads(path.read_text(encoding="utf-8"))["cases"]:
            cases.append({**raw, "suite": suite})
    return cases


def _constant(module: str, name: str) -> str:
    text = (ROOT / "personal_agent_protocol" / module).read_text(encoding="utf-8")
    match = re.search(rf"^{name}\s*=\s*[\"']([^\"']+)", text, re.MULTILINE)
    if match is None:
        raise SystemExit(f"{module} defines no {name}")
    return match[1]


def _version() -> str:
    return _constant("__version__.py", "__version__")


_PROFILE = _constant("profile.py", "PROTOCOL_PROFILE")
_REVISION = _constant("profile.py", "PROTOCOL_REVISION")
_OPERATIONS = _constant("operations.py", "OPERATIONS_VERSION")


def _load(directory: Path) -> dict[str, dict[str, Any]]:
    reports: dict[str, dict[str, Any]] = {}
    for stem, _, _ in PAIRINGS:
        path = directory / f"{stem}.json"
        if path.exists():
            document = json.loads(path.read_text(encoding="utf-8"))
            if document.get("schema_version") != 1:
                raise SystemExit(f"{path}: unsupported report schema")
            # A world's cases, run in a report of their own (`{stem}.{world}.json`).
            for extra in sorted(directory.glob(f"{stem}.*.json")):
                for key, value in json.loads(extra.read_text(encoding="utf-8"))["summary"].items():
                    document["summary"][key] += value
                document["cases"] += json.loads(extra.read_text(encoding="utf-8"))["cases"]
            reports[stem] = document
    if not reports:
        raise SystemExit(f"no conformance reports in {directory}")
    return reports


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _reasons(reports: dict[str, dict[str, Any]], columns: list[tuple[str, str, str]]) -> list[str]:
    """Each skip or failure reason, and the pairings it happened in."""

    reasons: dict[str, set[str]] = {}
    for stem, agent, company in columns:
        for item in reports[stem]["cases"]:
            if item["outcome"] != "passed" and item.get("message"):
                key = f"{item['outcome']}: {item['message']}"
                reasons.setdefault(key, set()).add(f"{agent} → {company}")
    if not reasons:
        return []
    lines = [
        "",
        "## Skips and failures",
        "",
        "| Outcome and reason | Pairings |",
        "| --- | --- |",
    ]
    for reason in sorted(reasons):
        lines.append(f"| {_cell(reason)} | {', '.join(sorted(reasons[reason]))} |")
    return lines


def render(reports: dict[str, dict[str, Any]]) -> str:
    fixtures = _fixtures()
    company_cases = [case for case in fixtures if "check" not in case]
    local_cases = [case for case in fixtures if "check" in case]
    columns = [(stem, agent, company) for stem, agent, company in PAIRINGS if stem in reports]
    outcomes = {
        stem: {item["id"]: item for item in reports[stem]["cases"]} for stem, _, _ in columns
    }
    lines = [
        "---",
        "title: Compatibility and conformance report",
        "---",
        "",
        "{/* Generated by scripts/conformance_report.py from the runners' JSON reports. */}",
        "",
        "# Compatibility and conformance report",
        "",
        f"SDK version **{_version()}**, PAP profile **{_PROFILE}** (draft updated "
        f"{_REVISION}), Operations extension **v{_OPERATIONS}**. Each pairing runs every "
        "positive, negative and recovery fixture case over real TCP and TLS, the personal "
        "agent in one language and the reference company (Manzanita) in the other. A case "
        "is skipped, never passed, when a side lacks what it needs; the reason is listed "
        "below.",
        "",
        "## Pairings",
        "",
        "| Personal agent | Company | Passed | Failed | Skipped |",
        "| --- | --- | ---: | ---: | ---: |",
    ]
    for stem, agent, company in columns:
        summary = reports[stem]["summary"]
        lines.append(
            f"| {agent} | {company} | {summary['passed']} | {summary['failed']} "
            f"| {summary['skipped']} |"
        )
    missing = [f"{agent} ↔ {company}" for stem, agent, company in PAIRINGS if stem not in reports]
    if missing:
        lines += ["", f"Not run for this report: {', '.join(missing)}."]
    header = " | ".join(f"{agent} → {company}" for _, agent, company in columns)
    for suite in SUITES:
        cases = [case for case in company_cases if case["suite"] == suite]
        if not cases:
            continue
        lines += [
            "",
            f"## {'DPoP' if suite == 'dpop' else suite.capitalize()}",
            "",
            f"| Case | Kind | Requirements | {header} |",
            "| --- | --- | --- | " + " | ".join("---" for _ in columns) + " |",
        ]
        for case in cases:
            cells = []
            for stem, _, _ in columns:
                result = outcomes[stem].get(case["id"])
                cells.append(OUTCOME[result["outcome"]] if result else "n/a")
            requirements = ", ".join(case.get("requirements", []))
            lines.append(
                f"| `{case['id']}` | {case['kind']} | {requirements} | {' | '.join(cells)} |"
            )
    lines += _reasons(reports, columns)
    lines += [
        "",
        "## Decided by each SDK alone",
        "",
        f"{len(local_cases)} fixture cases need no company: parsing, extension negotiation, "
        "URL safety and bounded discovery. Python runs them in `test_fixtures.py` and "
        "TypeScript in `conformance-fixtures.test.mjs`; a case marked for one SDK only is "
        "listed with it.",
        "",
        "| Case | Kind | Check | SDKs |",
        "| --- | --- | --- | --- |",
    ]
    for case in local_cases:
        sdks = ", ".join(case.get("sdk", ["python", "typescript"]))
        lines.append(f"| `{case['id']}` | {case['kind']} | {case['check']} | {sdks} |")
    lines += [
        "",
        "The runners' JSON reports (schema 1) carry each case's requirements and "
        "messages; see the [conformance guide](/guides/conformance/).",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("reports", type=Path, help="directory of the runners' JSON reports")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--check", action="store_true", help="fail if the page differs from the reports"
    )
    args = parser.parse_args(argv)
    page = render(_load(args.reports))
    if args.check:
        current = args.output.read_text(encoding="utf-8") if args.output.exists() else ""
        if current != page:
            sys.stderr.write(f"{args.output} is stale: run scripts/conformance_report.py\n")
            return 1
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(page, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
