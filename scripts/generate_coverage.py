"""Generate the protocol coverage reference from the requirement ledger.

`protocol/requirements.yaml` has one entry per normative statement of PAP draft 0.1
and Operations v1, and the Guides' recommendations apart. This script writes one
page per area under `docs/docs/protocol/coverage/` — every entry with its upstream
section, normative level, SDK symbols, test IDs and status — and the summary table
between the markers of `docs/docs/protocol/coverage.mdx`.

    python scripts/generate_coverage.py          # write the pages
    python scripts/generate_coverage.py --check  # fail when a page is stale (CI)
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Callable, Iterable
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
LEDGER = ROOT / "protocol" / "requirements.yaml"
DOCS = ROOT / "docs" / "docs" / "protocol"
HUB = DOCS / "coverage.mdx"
BEGIN = "{/* coverage:begin (generated by scripts/generate_coverage.py) */}"
END = "{/* coverage:end */}"
REPOSITORY = "https://github.com/datalayer/personal-agent-protocol/blob/main"
STATUSES = ("implemented", "partial", "open", "not-applicable")


def _major(section: str) -> str:
    return section.split(".", 1)[0]


def _spec(*sections: str) -> Callable[[dict[str, Any]], bool]:
    def matches(entry: dict[str, Any]) -> bool:
        return entry["source"] == "spec" and (
            entry["section"] in sections or _major(entry["section"]) in sections
        )

    return matches


@dataclass(frozen=True)
class Area:
    slug: str
    title: str
    summary: str
    upstream: str
    selects: Callable[[dict[str, Any]], bool]


AREAS = (
    Area(
        "discovery",
        "Discovery",
        "Company discovery, OAuth metadata, versions, and extensions (§3).",
        "https://personalagentprotocol.org/docs/spec",
        _spec("3"),
    ),
    Area(
        "identity-sessions",
        "Identity and Sessions",
        "Personal-agent and user identity, Sessions, and proof of possession (§4.1 to §4.3).",
        "https://personalagentprotocol.org/docs/spec",
        _spec("4.1", "4.2", "4.3"),
    ),
    Area(
        "sign-in",
        "Sign-in and Account Tokens",
        "Sign-in modes, consent, Account Tokens, and sign-out (§4.4 to §4.9).",
        "https://personalagentprotocol.org/docs/spec",
        _spec("4.4", "4.5", "4.6", "4.7", "4.8", "4.9"),
    ),
    Area(
        "browser",
        "Browser",
        "Joining a Session in the personal agent's own browser (§5).",
        "https://personalagentprotocol.org/docs/spec",
        _spec("5"),
    ),
    Area(
        "apis",
        "APIs",
        "OpenAPI with DPoP and MCP with a resource-bound Bearer (§6).",
        "https://personalagentprotocol.org/docs/spec",
        _spec("6"),
    ),
    Area(
        "conversations",
        "Conversations",
        "Messages, events, streaming, handoff, Direct Conversations, and closing (§7).",
        "https://personalagentprotocol.org/docs/spec",
        _spec("7"),
    ),
    Area(
        "operations",
        "Operations",
        "The Operations extension, version 1.",
        "https://personalagentprotocol.org/docs/extensions/operations",
        lambda entry: entry["source"] == "operations",
    ),
    Area(
        "operational-guidance",
        "Operational guidance",
        "The Guides' recommendations (SHOULD), kept apart from the specification.",
        "https://personalagentprotocol.org/docs/guides",
        lambda entry: entry["source"] == "guide",
    ),
)


def _entries() -> list[dict[str, Any]]:
    document = yaml.safe_load(LEDGER.read_text(encoding="utf-8"))
    entries = []
    for item in document.get("requirements", []):
        entries.append({**item, "source": item.get("source", "spec")})
    for item in document.get("guide", []):
        entries.append({**item, "source": "guide"})
    return entries


def _text(value: str) -> str:
    """Markdown-table and MDX-safe text."""

    return (
        value.replace("\\", "\\\\")
        .replace("|", "\\|")
        .replace("{", "\\{")
        .replace("}", "\\}")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace("\n", " ")
    )


def _symbol(reference: str) -> str:
    module, _, symbol = reference.partition(":")
    path = module.replace(".", "/") + ".py"
    if not (ROOT / path).exists():
        path = module.replace(".", "/") + "/__init__.py"
    name = symbol or module.rsplit(".", 1)[-1]
    return f"[`{name}`]({REPOSITORY}/{path})"


def _test(reference: str) -> str:
    path, _, name = reference.partition("::")
    return f"[`{Path(path).name}::{name}`]({REPOSITORY}/{path})" if name else f"`{path}`"


def _list(items: Iterable[str]) -> str:
    return "<br/>".join(items) or "—"


def _section(entry: dict[str, Any]) -> str:
    if entry["source"] == "guide":
        return _text(entry["section"])
    prefix = "Ops §" if entry["source"] == "operations" else "§"
    return f"{prefix}{entry['section']}"


def _status(entry: dict[str, Any]) -> str:
    status = f"**{entry['status']}**" if entry["status"] != "implemented" else "implemented"
    reason = entry.get("reason")
    return f"{status}: {_text(reason)}" if reason else status


def _counts(entries: list[dict[str, Any]]) -> dict[str, int]:
    return {status: sum(entry["status"] == status for entry in entries) for status in STATUSES}


def render_area(area: Area, entries: list[dict[str, Any]]) -> str:
    counts = _counts(entries)
    lines = [
        "---",
        f"title: {area.title} coverage",
        "---",
        "",
        "{/* Generated by scripts/generate_coverage.py from protocol/requirements.yaml. */}",
        "",
        f"# {area.title} coverage",
        "",
        f"{area.summary} Upstream: [{area.upstream.split('//', 1)[1]}]({area.upstream}).",
        "",
        f"{len(entries)} entries: "
        + ", ".join(f"{counts[status]} {status}" for status in STATUSES if counts[status])
        + ". Each row is one atomic statement of the upstream text, with the SDK symbols "
        "that implement it (Python; TypeScript mirrors them), the tests and shared "
        "conformance cases that show it, and its status.",
        "",
        "| ID | Section | Level | Role | Requirement | SDK symbol | Tests | Status |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for entry in entries:
        tests = [_test(test) for test in entry.get("tests", [])]
        tests += [f"`{case}`" for case in entry.get("conformance", [])]
        lines.append(
            f"| `{entry['id']}` | {_section(entry)} | {entry['level']} | {entry['role']} "
            f"| {_text(entry['text'])} "
            f"| {_list(_symbol(item) for item in entry.get('implementation', []))} "
            f"| {_list(tests)} | {_status(entry)} |"
        )
    lines += [
        "",
        "Conformance case IDs name `protocol/fixtures/conformance` cases; see the "
        "[conformance report](/protocol/conformance-report/) for their outcome in every "
        "language pairing.",
        "",
    ]
    return "\n".join(lines)


def render_hub(grouped: dict[str, list[dict[str, Any]]]) -> str:
    lines = [
        BEGIN,
        "",
        "| Area | Entries | Implemented | Partial | Open | Not applicable |",
        "| --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    for area in AREAS:
        entries = grouped[area.slug]
        counts = _counts(entries)
        lines.append(
            f"| [{area.title}](/protocol/coverage/{area.slug}/) | {len(entries)} "
            f"| {counts['implemented']} | {counts['partial']} | {counts['open']} "
            f"| {counts['not-applicable']} |"
        )
    lines += ["", END]
    return "\n".join(lines)


def pages() -> dict[Path, str]:
    entries = _entries()
    grouped: dict[str, list[dict[str, Any]]] = {area.slug: [] for area in AREAS}
    for entry in entries:
        matches = [area for area in AREAS if area.selects(entry)]
        if len(matches) != 1:
            raise SystemExit(f"{entry['id']} belongs to {len(matches)} coverage areas")
        grouped[matches[0].slug].append(entry)
    output = {
        DOCS / "coverage" / f"{area.slug}.mdx": render_area(area, grouped[area.slug])
        for area in AREAS
    }
    hub = HUB.read_text(encoding="utf-8")
    if BEGIN not in hub or END not in hub:
        raise SystemExit(f"{HUB} has no coverage markers")
    head, rest = hub.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    output[HUB] = head + render_hub(grouped) + tail
    return output


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when a page is stale")
    args = parser.parse_args(argv)
    stale = []
    for path, text in pages().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if stale:
        sys.stderr.write("stale coverage pages (run scripts/generate_coverage.py):\n")
        sys.stderr.write("".join(f"  {path}\n" for path in stale))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
